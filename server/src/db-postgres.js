export async function listCampaignsByUser(userId, limit = 50) {
  const { rows } = await q(
    "SELECT * FROM campaigns WHERE user_id = $1 ORDER BY id DESC LIMIT $2",
    [Number(userId), limit]
  );

  const map = await historyFor(rows.map((r) => r.id));
  return rows.map((r) => rowToCampaign(r, map.get(String(r.id)) || []));
}

export async function setCampaignStatus(code, status, actor, note = "") {
  const row = await one("SELECT * FROM campaigns WHERE code = $1", [String(code)]);
  if (!row) return null;
  if (row.status === status) return withHistory(row);

  const t = now();
  const updated = await one(
    "UPDATE campaigns SET status = $1, updated_at = $2 WHERE id = $3 RETURNING *",
    [status, t, row.id]
  );

  await q(
    "INSERT INTO campaign_events (campaign_id, status, note, actor, at) VALUES ($1, $2, $3, $4, $5)",
    [row.id, status, note, actor, t]
  );

  return withHistory(updated);
}

export async function setCampaignStats(code, views, clicks, joins) {
  const row = await one("SELECT * FROM campaigns WHERE code = $1", [String(code)]);
  if (!row) return null;

  const updated = await one(
    "UPDATE campaigns SET views = $1, clicks = $2, joins = $3, updated_at = $4 WHERE id = $5 RETURNING *",
    [Number(views) || 0, Number(clicks) || 0, Number(joins) || 0, now(), row.id]
  );

  return withHistory(updated);
}

