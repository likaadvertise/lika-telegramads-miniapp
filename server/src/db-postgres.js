/* =========================================================
   دیتابیس — نسخهٔ Postgres
   ---------------------------------------------------------
   این نسخه وقتی به کار می‌رود که POSTGRES_URL (یا DATABASE_URL)
   تنظیم شده باشد — یعنی روی Vercel.

   چرا لازم شد؟ روی Vercel دیسک ماندگار وجود ندارد، پس فایل
   SQLite پاک می‌شود. Postgres یک دیتابیس جدا و ماندگار است.

   کتابخانهٔ pg با import پویا بارگذاری می‌شود تا نسخهٔ SQLite
   همچنان بدون هیچ وابستگی npm کار کند.
   ========================================================= */

