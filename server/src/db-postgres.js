export async function issuePhoneCode(userId, phone) {
  const existing = await one("SELECT * FROM phone_codes WHERE user_id = $1", [Number(userId)]);

  if (existing) {
    const since = (Date.now() - new Date(existing.sent_at).getTime()) / 1000;
    if (since < CODE_RESEND_SECONDS) {
      return { ok: false, retryAfter: Math.ceil(CODE_RESEND_SECONDS - since) };
    }
  }

  const code = makeCode();
  const expiresAt = new Date(Date.now() + CODE_TTL_MINUTES * 60000).toISOString();

  await q(
    `INSERT INTO phone_codes (user_id, phone, code_hash, expires_at, attempts, sent_at)
     VALUES ($1, $2, $3, $4, 0, $5)
     ON CONFLICT (user_id) DO UPDATE SET
       phone      = EXCLUDED.phone,
       code_hash  = EXCLUDED.code_hash,
       expires_at = EXCLUDED.expires_at,
       attempts   = 0,
       sent_at    = EXCLUDED.sent_at`,
    [Number(userId), phone, hashCode(userId, code), expiresAt, now()]
  );

  return {
    ok: true,
    code,
    expiresInSeconds: CODE_TTL_MINUTES * 60,
    resendAfterSeconds: CODE_RESEND_SECONDS
  };
}

export async function checkPhoneCode(userId, code) {
  const row = await one("SELECT * FROM phone_codes WHERE user_id = $1", [Number(userId)]);
  if (!row) return { ok: false, error: CODE_ERRORS.notSent };

  const clear = () => q("DELETE FROM phone_codes WHERE user_id = $1", [Number(userId)]);

  if (new Date(row.expires_at).getTime() < Date.now()) {
    await clear();
    return { ok: false, error: CODE_ERRORS.expired };
  }

  if (Number(row.attempts) >= CODE_MAX_ATTEMPTS) {
    await clear();
    return { ok: false, error: CODE_ERRORS.tooManyAttempts };
  }

  if (!codeMatches(userId, code, row.code_hash)) {
    await q("UPDATE phone_codes SET attempts = attempts + 1 WHERE user_id = $1", [Number(userId)]);
    return { ok: false, error: CODE_ERRORS.wrong(CODE_MAX_ATTEMPTS - (Number(row.attempts) + 1)) };
  }

  await clear();
  await q("UPDATE users SET phone = $1 WHERE id = $2", [row.phone, Number(userId)]);
  return { ok: true, phone: row.phone };
}

