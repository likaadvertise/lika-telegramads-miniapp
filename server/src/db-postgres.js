export async function setCampaignReceipt(code, fileId) {
  const t = now();
  const row = await one(
    `UPDATE campaigns SET receipt_file_id = $1, receipt_at = $2, updated_at = $2
     WHERE code = $3 RETURNING *`,
    [String(fileId), t, String(code)]
  );
  return row ? withHistory(row) : null;
}
