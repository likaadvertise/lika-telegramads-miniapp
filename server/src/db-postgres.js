/** ویرایش سفارش توسط مدیر — همان رکوردی که مشتری می‌بیند */
export async function editCampaign(code, d, actor = "مدیر") {
  const row = await one("SELECT * FROM campaigns WHERE code = $1", [String(code)]);
  if (!row) return null;

  const t = now();
  await q(
    `UPDATE campaigns SET
       ad_title = $1, brand = $2, target_url = $3, ad_text = $4,
       channels = $5, keywords = $6,
       status = $7, admin_note = $8, updated_at = $9
     WHERE code = $10`,
    [d.adTitle, d.brand, d.targetUrl, d.adText,
     JSON.stringify(d.channels), JSON.stringify(d.keywords),
     d.status, d.adminNote, t, String(code)]
  );

  await q(
    "INSERT INTO campaign_events (campaign_id, status, note, actor, at) VALUES ($1, $2, $3, $4, $5)",
    [row.id, d.status, d.adminNote || "ویرایش توسط تیم", actor, t]
  );

  const fresh = await one("SELECT * FROM campaigns WHERE code = $1", [String(code)]);
  const map = await historyFor([fresh.id]);
  return rowToCampaign(fresh, map.get(String(fresh.id)) || []);
}

